nx1=[0:4];
x1=[1 1 1 1 1];
h1=[1 -1 3 0 1];
h2=[0 2 5 4 -1];
nw=[0:8];
w=conv(x1,h1);
nw=[0:length(w)-1];
figure(1);
stem(nw,w);
xlabel('n');
ylabel('w[n]');
title('The figure of the signal w[n]=x1[n]*h1[n]');
grid on;
yd1=conv(w,h2);
nyd1=[0:length(yd1)-1];
figure(2);
stem(nyd1,yd1);
xlabel('n');
ylabel('yd1[n]');
title('The figure of the signal yd1[n]=w1[n]*h2[n]');
grid on;
hs=conv(h1,h2);
nhs=[0:length(hs)-1];
