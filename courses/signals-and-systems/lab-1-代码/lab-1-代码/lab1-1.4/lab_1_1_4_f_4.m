% (4)	Prove the system is linear:
n=[-10:10];
x1=[zeros(1,10) 1 zeros(1,10)];
x2=[zeros(1,8) 1 zeros(1,12)];
subplot(4,2,1);
stem(n,x1);xlabel('n');ylabel('x1[n]');title('The figure of the signal x1[n]');
grid on;
y1=n.*x1;
subplot(4,2,2);
stem(n,y1);xlabel('n');ylabel('y1[n]');title('The figure of the signal y1[n]');
grid on;
subplot(4,2,3);
stem(n,x2);xlabel('n');ylabel('x2[n]');title('The figure of the signal x2[n]');
grid on;
y2=n.*x2;
subplot(4,2,4);
stem(n,y2);xlabel('n');ylabel('y2[n]');title('The figure of the signal y2[n]');
grid on;
x3=2*x1+3*x2;
subplot(4,2,5);
stem(n,x3);xlabel('n');ylabel('x3[n]');title('The figure of the signal x3[n]');
grid on;
y3=n.*x3;
subplot(4,2,6);
stem(n,y3);xlabel('n');ylabel('y1[n+2]');title('The figure of the signal y3');
y4=2*y1+3*y2;
subplot(4,2,7);
stem(n,y4);xlabel('n');ylabel('y1[n+2]');title('The figure of the signal y4');
grid on;