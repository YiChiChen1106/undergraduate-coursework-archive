n=[-10:10];
x1=[zeros(1,10) 1 zeros(1,10)];
x2=[zeros(1,10) 2 zeros(1,10)];
y1=sin(pi/2*x1);
y2=sin(pi/2*x2);
figure(1);
subplot(2,2,1);
stem(n,x1),xlabel('n');ylabel('x1[n]');title('The figure of the signalx1[n]');
grid on;
subplot(2,2,2);
stem(n,x2);xlabel('n');ylabel('x2[n]');title('The figure of the signalx2[n]');
grid on;
subplot(2,2,3);
stem(n,y1);xlabel('n');ylabel('y1[n]');title('The figure of the signaly1[n]');
grid on;
subplot(2,2,4);
stem(n,y2);xlabel('n');ylabel('y2[n]');title('The figure of the signaly2[n]');
grid on;
axis([-10,10,0,1]);
x3=x1+x2;
y3=sin(pi/2*x3);
figure(2);
subplot(2,2,1);
stem(n,x3);xlabel('n');ylabel('x3[n]');title('The figure of the signalx3[n]');
grid on;
subplot(2,2,2);
stem(n,x1+x2);xlabel('n');ylabel('x1[n]+x2[n]');title('The figure of the signalx1[n]+x2[n]');
grid on;
subplot(2,2,3);
stem(n,y3);xlabel('n');ylabel('y3[n]');title('The figure of the signaly3[n]');
grid on;
subplot(2,2,4);
stem(n,y1+y2);xlabel('n');ylabel('y1[n]+y2[n]');title('The figure of the signaly1[n]+y2[n]');
grid on;